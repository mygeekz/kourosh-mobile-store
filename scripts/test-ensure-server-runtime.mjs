import assert from 'node:assert/strict';
import http from 'node:http';
import { EventEmitter } from 'node:events';
import { probeExistingKouroshApi, ensureServerRuntime } from './ensure-server-runtime.mjs';
const server = http.createServer();
let body = { success: false, code: 'MINIAPP_INIT_DATA_INVALID', requestId: 'fixture' };
server.on('request', (req, res) => { req.resume(); res.writeHead(401, { 'content-type': 'application/json' }); res.end(JSON.stringify(body)); });
await new Promise(r => server.listen(0, '127.0.0.1', r));
const port = server.address().port;
assert.equal(await probeExistingKouroshApi({port}), 'kourosh');
body = { success: true, message: 'another service' };
assert.equal(await probeExistingKouroshApi({port}), 'occupied');
await new Promise(r => server.close(r));
assert.equal(await probeExistingKouroshApi({port}), 'free');
let spawned = 0;
await assert.rejects(ensureServerRuntime({probe:async()=> 'occupied',spawnRuntime:()=>{spawned++;}}));
const signals = new EventEmitter();
const reused = ensureServerRuntime({probe:async()=> 'kourosh',signals,intervalMs:5,spawnRuntime:()=>{spawned++;},report:()=>{}});
await new Promise(r=>setTimeout(r,25));
assert.equal(spawned,0);
signals.emit('SIGTERM'); assert.equal(await reused,0);
assert.equal(signals.listenerCount('SIGTERM'),0);
assert.equal(await ensureServerRuntime({probe:(()=>{let n=0;return async()=>n++===0?'kourosh':'free';})(),intervalMs:1,report:()=>{}}),1);
const child = new EventEmitter(); child.kill = () => child.emit('exit',0);
const owned = ensureServerRuntime({probe:async()=> 'free',spawnRuntime:()=>{spawned++;setImmediate(()=>child.emit('exit',0));return child;},report:()=>{}});
assert.equal(await owned,0); assert.equal(spawned,1);
console.log('PASS runtime reuse, unknown service rejection, free port startup, health loss and graceful shutdown');
