import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const version=read('KOUROSH_SOURCE_VERSION').trim();
const n=Number(version.replace(/^v/,''));
assert.ok(Number.isInteger(n)&&n>=344,`KOUROSH_SOURCE_VERSION must be v344 or successor; found ${version}`);
const backend=read('server/accounting/accountingDrilldown.ts');
const routes=read('server/routes/accountingReconciliation.routes.ts');
const page=read('pages/AccountingDrilldownPage.tsx');
const customer=read('pages/customerDetail/CustomerDetailHeroOverviewSection.tsx');
const installment=read('pages/InstallmentSaleDetailPage.tsx');
const invoice=read('pages/InvoiceDetail.tsx');
const partner=read('pages/partnerDetail/PartnerAccountingBreakdownSection.tsx');
const manifest=read('app/routes/routeManifest.tsx');
for (const kind of ['customer','partner','installment','sale','profit']) assert.match(backend,new RegExp(`kind === '${kind}'`),`missing drilldown kind ${kind}`);
assert.match(backend,/runningBalance/);
assert.match(backend,/calculateInstallmentContractAccountingState/);
assert.match(routes,/drilldown\/:kind\/:id/);
assert.match(page,/مسیر رسیدن به عدد/);
assert.match(page,/اسناد تشکیل‌دهنده/);
assert.match(customer,/accounting-drilldown\/customer/);
assert.match(installment,/accounting-drilldown\/installment/);
assert.match(invoice,/accounting-drilldown\/sale/);
assert.match(partner,/Drill-down طلب تأمین‌کنندگی/);
assert.match(partner,/Drill-down سهم سود \/ مالکیت/);
assert.match(manifest,/accounting-drilldown\/:kind\/:id/);
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.scripts['audit:accounting-drilldown-v344'],'node scripts/audit-accounting-drilldown-v344.mjs');
console.log(JSON.stringify({ok:true,domains:5,checks:17},null,2));
