import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const version=read('KOUROSH_SOURCE_VERSION').trim();
const n=Number(version.replace(/^v/,''));
assert.ok(Number.isInteger(n)&&n>=345,`KOUROSH_SOURCE_VERSION must be v345 or successor; found ${version}`);
const core=read('shared/accounting/accountingCore.ts');
const engine=read('server/accounting/accountingEngine.ts');
const governance=read('server/accounting/accountingGovernance.ts');
const routes=read('server/routes/partners.routes.ts');
const controller=read('pages/partnerDetail/PartnerDetailController.tsx');
const section=read('pages/partnerDetail/PartnerAccountingBreakdownSection.tsx');
assert.match(core,/inspectAccountingMovementForRead/,'legacy-safe read inspection must live in Accounting Core');
assert.match(engine,/inspectAccountingMovementForRead/,'server Accounting Engine must re-export the read inspection helper');
assert.match(governance,/PRAGMA table_info\(partner_ledger\)/,'partner breakdown must project legacy schemas defensively');
assert.match(governance,/legacyMovementIssueCount/,'partner breakdown must expose legacy movement anomalies without crashing');
assert.doesNotMatch(governance,/accountingMovementDelta\(\"partner\", \{ debit: totalPayments, credit: totalIncreases \}\)/,'aggregate debit/credit totals must never be revalidated as one movement');
assert.match(governance,/canonicalBalance = entries\.reduce/,'canonical partner balance must be the sum of row deltas');
assert.match(governance,/inspectAccountingMovementForRead\("partner"/,'partner breakdown must use central accounting read inspection');
assert.match(routes,/\/api\/partners\/:id\/accounting-breakdown/,'canonical breakdown route must exist');
assert.match(routes,/\/api\/partners\/:id\/counting-breakdown/,'stale-PWA compatibility alias must exist');
assert.match(routes,/handlePartnerAccountingBreakdown/,'both breakdown routes must share one handler');
assert.match(controller,/Profile is the primary resource; accounting breakdown is supplemental/,'profile load must not depend on supplemental drill-down');
assert.match(controller,/partnerAccountingBreakdownError/,'breakdown failure state must be recoverable in UI');
assert.doesNotMatch(controller,/if \(!accountingResponse\.ok \|\| !accountingResult\.success\) throw/,'supplemental breakdown failure must not throw the whole partner page');
assert.match(section,/data-partner-accounting-breakdown="degraded"/,'degraded breakdown state must be visible instead of blanking the page');
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.scripts['audit:partner-accounting-breakdown-hotfix-v345'],'node scripts/audit-partner-accounting-breakdown-hotfix-v345.mjs');
assert.match(pkg.scripts['audit:release'],/audit:partner-accounting-breakdown-hotfix-v345/,'v345 guard must be in audit:release');
console.log(JSON.stringify({ok:true,release:version,checks:16},null,2));
