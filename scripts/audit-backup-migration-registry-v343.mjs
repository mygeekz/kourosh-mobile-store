import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=(p)=>fs.readFileSync(p,'utf8');
const version=read('KOUROSH_SOURCE_VERSION').trim();
const n=Number(version.replace(/^v/,''));
assert.ok(Number.isInteger(n)&&n>=343,`KOUROSH_SOURCE_VERSION must be v343 or successor; found ${version}`);
const runner=read('server/utils/migrationRunner.ts');
const app=read('server/app.ts');
const backup=read('server/backup.ts');
const backupRoutes=read('server/routes/backup.routes.ts');
const ui=read('pages/settings/SettingsDataPanel.tsx');
assert.match(runner,/affectedRows/);
assert.match(runner,/result TEXT/);
assert.match(runner,/backupFileName/);
assert.match(runner,/backupSha256/);
assert.match(runner,/beforeApplyBatch/);
assert.match(runner,/safety backup is missing or its SHA256 was not verified/);
assert.match(app,/pre-migration/);
assert.match(app,/createDbBackup/);
assert.match(backup,/checksumVerified/);
assert.match(backupRoutes,/pre-restore/);
assert.match(ui,/SHA256:/);
assert.match(ui,/verified/);
const pkg=JSON.parse(read('package.json'));
assert.equal(pkg.scripts['test:migration-registry-safety-v343'],'node --experimental-strip-types server/tests/migrationRegistrySafetyV343.test.mjs');
console.log(JSON.stringify({ok:true,checks:13},null,2));
